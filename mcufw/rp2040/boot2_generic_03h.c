/* RP2040 second-stage bootloader: generic_03h.
 *
 * plain 03h serial read - the universal, slowest path.
 *
 * WHAT THIS FILE IS AND WHY IT IS BYTES. The bootrom copies the first 256
 * bytes of flash into SRAM at 0x20041F00, checks that the last word is a
 * CRC-32/MPEG-2 over the preceding 252, runs it, and expects it to have
 * configured the QSPI link and jumped to 0x10000100. Without a valid boot2
 * there is no XIP, so there is no image: the part comes up in USB bootloader
 * mode and from the host that looks like a board that never says hello.
 *
 * The checksum is over the ASSEMBLED BYTES, so it cannot be computed at link
 * time - build.mk has no post-link hook and is shared by every part, so this
 * port has no business growing one. The bytes are therefore carried as bytes,
 * with the checksum already in them, and they are the same bytes whatever
 * compiler builds this tree. That is the point: a blob and its checksum
 * cannot drift apart, and a re-assembled boot2 and a stale checksum can.
 *
 * PROVENANCE, exactly. These are the bytes the research tree's RP2040 rig has
 * been running on silicon - pico-sdk's src/rp2040/boot_stage2/boot2_generic_03h.S,
 * assembled and then padded and checksummed by the SDK's own
 * pad_checksum, taken from
 * rigs/fw_rp2040_aes/build/branchless-a0-generic_03h-O2/sel_boot2_padded_checksummed.S.
 * Second-stage loader code (c) Raspberry Pi Ltd, BSD-3-Clause.
 *
 * It is 256 bytes of loader, not a vendored SDK: nothing in this tree needs
 * the SDK to build, and writing a QSPI second stage from the datasheet
 * instead would be a guess with no board to try it on.
 *
 * Checksum in these bytes: 0x5d4c22ea (verified: CRC-32/MPEG-2 over bytes
 * 0..251 equals the stored word at offset 252). mcufw/rp2040/regs.h folds the
 * low 24 bits of it into the accelerator word, so the device reports which
 * boot2 is PHYSICALLY in flash rather than which one a -D claimed.
 *
 * THIS IS THE GAIN KNOB ON THIS PART. There is no wait-state field anywhere;
 * the cost of a miss is the serial link's clock divider, dummy cycles and
 * sample delay, and all three are set here and nowhere else. The research
 * tree measured 2.77x between the two variants this port ships. Select with
 * BOOT2= in mcufw/rp2040/board.mk.
 */
